// The image an image-generation turn edits.
//
// One question, one answer: which image is this conversation's *current*
// image — the one a follow-up prompt ("now make it night", "remove the
// people") should be applied to?
//
// The app keeps no pointer to it. Every image lives on its own message
// (`imagePath` for a generated result, `attachments[]` for something the
// user dropped in), so the current image is *derived* from the transcript on
// every read. That is deliberate: a stored pointer would have to be kept
// correct by the delete, edit, switch and sync paths, and a derived answer
// cannot go stale.
//
// The rule (see docs/image-edit-context-spec.md §5.1):
//
//   1. Scan the transcript backwards.
//   2. The first message with a generated result wins — a result is the
//      picture the user is looking at.
//   3. Otherwise the first message with attachments wins, and within it the
//      first attachment: that is the primary subject, the rest are
//      secondary references.
//   4. No images at all → nothing to edit.
//
// A result beats the attachments that fed it: after an edit, the next prompt
// means the result, not the original. Falling back to the attachment would
// re-anchor the chain one step back, so "make it night" would edit the
// original rather than the night-ified version.

import type { ImageOrigin, Message } from "./backend";
import { isDataUrl } from "./dataUrl";

export interface CurrentImage {
  /**
   * The reference itself: a Drive path to read back, or a self-contained
   * data URI to send as-is.
   */
  ref: string;
  /** How `ref` has to be used. */
  kind: "drive" | "data";
  /** Whether it was attached by the user or generated by the app. */
  origin: ImageOrigin;
  /** Index of the message that holds it. */
  messageIndex: number;
}

/**
 * The newest image the conversation holds, or null when it holds none.
 */
export function findCurrentImage(messages: Message[]): CurrentImage | null {
  for (let i = messages.length - 1; i >= 0; i--) {
    const message = messages[i];
    if (!message) continue;
    if (message.imagePath) {
      return {
        ref: message.imagePath,
        kind: "drive",
        origin: "generated",
        messageIndex: i,
      };
    }
    // A legacy inline image, from before images were saved to Drive. Only a
    // data URI qualifies: it carries its own bytes, while a hosted URL may
    // be long gone — and the provider would fail to fetch it.
    if (message.image && isDataUrl(message.image)) {
      return {
        ref: message.image,
        kind: "data",
        origin: "generated",
        messageIndex: i,
      };
    }
    const attachment = message.attachments?.[0];
    if (attachment?.path) {
      return {
        ref: attachment.path,
        kind: "drive",
        origin: "attachment",
        messageIndex: i,
      };
    }
  }
  return null;
}
